  };

  /// Devuelve las líneas de diálogo de un [bloque] en una [semana] dadas, o
  /// null si ese bloque no existe en esa semana.
  static List<DialogoLinea>? lineasDe(int semana, String bloque) {
    return _guion[semana]?[bloque];
  }

