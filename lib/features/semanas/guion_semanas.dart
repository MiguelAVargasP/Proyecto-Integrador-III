  /// Construye un nodo de diálogo a partir de texto EXACTO del guion.
  ///
  /// Estructura (máxima fidelidad al documento, que NO incluye preguntas
  /// artificiales): la propia [narrativa] lleva adjuntas las dos opciones, y
  /// cada una salta a su línea de consecuencia.
  ///   - 0: narrativa + opciones. 1: respuesta op 1. 2: respuesta op 2.
  ///
  /// [pregunta] se acepta por compatibilidad con llamadas antiguas pero se
  /// ignora a propósito: el guion no trae preguntas inventadas, así que nunca
  /// se muestran como línea propia.
  ///
  /// [textoRespuesta1/2] son la reinterpretación breve, en primera persona,
  /// de la consecuencia que el propio guion describe entre paréntesis en cada
  /// opción (el guion no trae líneas de cierre literales, solo el paréntesis).
  static List<DialogoLinea> _nodo({
    required String contextoDecision,
    required String imagen,
    required String narrativa,
    String pregunta = '',
    required String textoOpcion1,
    required int delta1,
    required String textoRespuesta1,
    required String textoOpcion2,
    required int delta2,
    required String textoRespuesta2,
  }) {
    // 0: narrativa + opciones. 1: respuesta op 1. 2: respuesta op 2.
    return [
      DialogoLinea(
        narrativa,
        imagen: imagen,
        opciones: [
          OpcionDialogo(
            textoOpcion1,
            saltarA: 1,
            deltaEstres: delta1,
            decisionRegistrada: '[$contextoDecision] Eligió: $textoOpcion1',
          ),
          OpcionDialogo(
            textoOpcion2,
            saltarA: 2,
            deltaEstres: delta2,
            decisionRegistrada: '[$contextoDecision] Eligió: $textoOpcion2',
          ),
        ],
      ),
      DialogoLinea(textoRespuesta1, imagen: imagen, esFinal: true),
      DialogoLinea(textoRespuesta2, imagen: imagen, esFinal: true),
    ];
  }

